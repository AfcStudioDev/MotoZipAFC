-- ============================================================
-- Очистка "осиротевших" покупок (Purchase без единой позиции Order).
--
-- Причина: до фикса в AdminDeleteController удаление последнего заказа
-- покупки через админ-панель удаляло строку Order, но не саму Purchase.
-- Такая Purchase больше не видна во вкладке «Заказы» (там показываются
-- строки Order), но всё ещё ссылается на DeliveryAddress и блокирует
-- его удаление ("На этот адрес оформлены заказы: N").
--
-- Скрипт ничего не делает сам по себе — выполняйте секции по очереди
-- и проверяйте результат перед COMMIT.
-- ============================================================

-- 1) ПРЕДПРОСМОТР. Ничего не меняет. Посмотрите на список — это и есть
--    те самые "фантомные" покупки, которые сейчас блокируют удаление адресов.
SELECT
    p."Id",
    p."PurchaseNumber",
    p."AddressId",
    p."UserId",
    p."IsPaid",
    p."ReceiptFileName",
    p."OrderDateTime"
FROM "Purchases" p
WHERE NOT EXISTS (SELECT 1 FROM "Orders" o WHERE o."PurchaseId" = p."Id");

-- Если в списке выше есть строки с заполненным "ReceiptFileName" — соответствующий
-- файл в wwwroot/Receipts после удаления строки станет просто неиспользуемым файлом
-- на диске (ни на что не ссылается, ничего не ломает). Удалять его отдельно не обязательно.

-- 2) УДАЛЕНИЕ. Запускайте только после того, как проверили список из шага 1.
BEGIN;

DELETE FROM "Purchases" p
WHERE NOT EXISTS (SELECT 1 FROM "Orders" o WHERE o."PurchaseId" = p."Id");

-- Проверка: этот запрос должен вернуть 0 строк. Если так — можно COMMIT.
SELECT p."Id"
FROM "Purchases" p
WHERE NOT EXISTS (SELECT 1 FROM "Orders" o WHERE o."PurchaseId" = p."Id");

